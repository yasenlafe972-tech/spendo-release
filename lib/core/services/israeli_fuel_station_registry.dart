  /// Detects the fuel company name from Hebrew/Latin keywords, registration IDs, phone numbers, or Paz invoice format.
  static String detectCompany(String text) {
    final lower = text.toLowerCase();

    // 1. Check official registration numbers (ח.פ. / איחוד עוסקים) - 100% reliable even on Latin-only OCR!
    for (final entry in companyByRegistrationId.entries) {
      if (text.contains(entry.key)) {
        return entry.value;
      }
    }

    // 2. Check Paz-specific signatures (Paz customer service phone 03-6021814, Paz item 3951, or 15-digit Paz invoice 0XXX099XXXXXXXX)
    if (text.contains('03-6021814') ||
        text.contains('036021814') ||
        RegExp(r'\b3951\b').hasMatch(text) ||
        RegExp(r'(?<!\d)0\d{3}099\d{8}(?!\d)').hasMatch(text)) {
      return 'פז';
    }

    // 3. Check explicit company keywords
    if (text.contains('פז') ||
        lower.contains('yellow') ||
        lower.contains('paz') ||
        text.contains('ילאו') ||
        text.contains('ילו')) {
      return 'פז';
    }
    if (text.contains('סונול') || lower.contains('sonol') || lower.contains('so good')) {
      return 'סונול';
    }
    if (text.contains('דור אלון') ||
        text.contains('אלונית') ||
        lower.contains('dor alon') ||
        lower.contains('doralon') ||
        lower.contains('alonit')) {
      return 'דור אלון';
    }
    if (text.contains('דלק') && (text.contains('מנטה') || text.contains('חברת הדלק') || lower.contains('delek') || lower.contains('menta'))) {
      return 'דלק';
    }
    if (lower.contains('delek') || lower.contains('menta') || text.contains('מנטה')) {
      return 'דלק';
    }
    if (text.contains('מיקה') || lower.contains('mika')) {
      return 'מיקה';
    }
    if (text.contains('תפוז')) {
      return 'תפוז';
    }
    if (text.contains('סד"ש') || text.contains('סדש')) {
      return 'סד"ש';
    }
    if (RegExp(r'(?:^|\s)טן(?:\s|$)').hasMatch(text) || RegExp(r'\bten\b', caseSensitive: false).hasMatch(text)) {
      return 'טן';
    }
    if (text.contains('דלק')) {
      return 'דלק';
    }
    return '';
  }

  /// Resolves the exact gas station name and branch code from a receipt's text and/or invoice number.
  static String resolveStation({
    required String text,
    String? detectedCompany,
    String? invoiceNumber,
  }) {
    final company = (detectedCompany != null && detectedCompany.isNotEmpty)
        ? detectedCompany
        : detectCompany(text);

    // 1. Extract station code from parentheses on receipt header, e.g. "(422)" in "סניף: סכנין החדשה (422)"
    String? parenthesizedCode;
    for (final m in RegExp(r'\(\s*(\d{2,4})\s*\)').allMatches(text)) {
      final candidate = int.tryParse(m.group(1)!)?.toString();
      if (candidate == null) continue;
      // Ignore Israeli phone area codes and fuel octane numbers
      if (const {'02', '03', '04', '08', '09', '2', '3', '4', '8', '9', '95', '98', '17', '18'}.contains(candidate)) {
        continue;
      }
      parenthesizedCode = candidate;
      break;
    }

    // 2. Extract station code from 15-digit Paz fiscal invoice number: 0<3-digit-station><11-digits> (e.g. 042209901087851 -> 422)
    String? invoicePrefixCode;
    final invCandidates = <String>[
      if (invoiceNumber != null && invoiceNumber.isNotEmpty) invoiceNumber,
      ...RegExp(r'(?<!\d)(0\d{14})(?!\d)').allMatches(text).map((m) => m.group(1)!),
    ];
    for (final inv in invCandidates) {
      if (inv.length == 15 && inv.startsWith('0')) {
        final rawPrefix = inv.substring(1, 4);
        final parsedPrefix = int.tryParse(rawPrefix)?.toString();
        if (parsedPrefix != null && parsedPrefix.length >= 2) {
          invoicePrefixCode = parsedPrefix;
          break;
        }
      }
    }

    // 3. Extract station code from explicit Hebrew label: "סניף: 422" or "תחנה: 422" or "מס' תחנה: 422"
    String? labeledCode;
    final labeledCodeMatch = RegExp(
      r"""(?:סניף|תחנה|מס'?\s*תחנה|מספר\s*תחנה)[:\s#\-]*(\d{2,4})\b""",
    ).firstMatch(text);
    if (labeledCodeMatch != null) {
      labeledCode = int.tryParse(labeledCodeMatch.group(1)!)?.toString();
    }

    final stationCode = parenthesizedCode ?? invoicePrefixCode ?? labeledCode;

    // 4. Extract explicit Hebrew branch name from "סניף: סכנין החדשה (422)" or "תחנה: ..."
    String? explicitHebrewBranch;
    final branchPatterns = [
      RegExp(r'(?:סניף|שם\s*תחנה|תחנת\s*דלק|תחנת\s*תדלוק|תחנה)\s*[:\-]\s*([^\n\r]+)'),
      RegExp(r'([^\n\r:]{2,35}?)\s*:\s*(?:סניף|פזנס|תחנה)'),
    ];
    for (final pattern in branchPatterns) {
      final m = pattern.firstMatch(text);
      if (m != null) {
        var rawBranch = m.group(1)!.trim();
        // Strip trailing phone/invoice labels if merged onto same line
        rawBranch = rawBranch
            .split(RegExp(r'(?:טלפון|טל|חשבונית|ח\.פ|איחוד עוסקים)'))
            .first
            .trim();
        // Verify it contains at least 2 Hebrew characters
        if (RegExp(r'[\u0590-\u05FF]{2,}').hasMatch(rawBranch)) {
          explicitHebrewBranch = rawBranch;
          break;
        }
      }
    }

    // If explicit Hebrew branch was found on the receipt (e.g. "סכנין החדשה (422)"), format it cleanly!
    if (explicitHebrewBranch != null && explicitHebrewBranch.isNotEmpty) {
      var cleanBranch = explicitHebrewBranch
          .replaceAll('חברת נפט', '')
          .replaceAll('בע"מ', '')
          .replaceAll(RegExp(r'\s+'), ' ')
          .trim();
      // Normalize reversed parentheses if visual RTL flipped them, e.g. ")422( סכנין החדשה"
      cleanBranch = cleanBranch.replaceAllMapped(
        RegExp(r'\)(\d{2,4})\('),
        (m) => '(${m[1]})',
      );
      if (stationCode != null && !cleanBranch.contains(stationCode)) {
        cleanBranch = '$cleanBranch ($stationCode)';
      }
      final compPrefix = company.isNotEmpty ? company : 'פז';
      if (!cleanBranch.startsWith(compPrefix)) {
        return '$compPrefix $cleanBranch';
      }
      return cleanBranch;
    }

    // 5. Lookup station code in our official station registries!
    if (stationCode != null) {
      if (company == 'פז' || company.isEmpty) {
        final pazName = pazStationsByCode[stationCode];
        if (pazName != null) {
          return 'פז $pazName ($stationCode)';
        }
      }
      if (company == 'סונול' || company.isEmpty) {
        final sonolName = sonolStationsByCode[stationCode];
        if (sonolName != null) {
          return 'סונול $sonolName ($stationCode)';
        }
      }
      if (company == 'דלק' || company.isEmpty) {
        final delekName = delekStationsByCode[stationCode];
        if (delekName != null) {
          return 'דלק $delekName ($stationCode)';
        }
      }
      if (company == 'דור אלון' || company.isEmpty) {
        final dorName = dorAlonStationsByCode[stationCode];
        if (dorName != null) {
          return 'דור אלון $dorName ($stationCode)';
        }
      }
      if (company == 'מיקה' || company.isEmpty) {
        final mikaName = mikaStationsByCode[stationCode];
        if (mikaName != null) {
          return 'מיקה $mikaName ($stationCode)';
        }
      }
      if (company == 'תפוז' || company.isEmpty) {
        final tapuzName = tapuzStationsByCode[stationCode];
        if (tapuzName != null) {
          return 'תפוז $tapuzName ($stationCode)';
        }
      }
      final govName = govStationsByCode[stationCode];
      if (govName != null) {
        return '$govName ($stationCode)';
      }
      // Fallback if Paz station code is in Paz's map regardless of detectedCompany
      if (pazStationsByCode.containsKey(stationCode)) {
        return 'פז ${pazStationsByCode[stationCode]} ($stationCode)';
      }
      if (sonolStationsByCode.containsKey(stationCode)) {
        return 'סונול ${sonolStationsByCode[stationCode]} ($stationCode)';
      }
      // Even if a new station code isn't in the static map yet, preserve the station code!
      if (company.isNotEmpty) {
        return '$company סניף ($stationCode)';
      }
    }

    // 6. Check 13-digit StoreNext EDI barcode (7290058... / 7290172...)
    for (final m in RegExp(r'(?<!\d)(7290\d{9})(?!\d)').allMatches(text)) {
      final edi = m.group(1)!;
      final ediStation = stationsByEdi[edi];
      if (ediStation != null) {
        return ediStation;
      }
    }

    // 7. Check local station phone number (excluding Paz corporate 03-6021814)
    for (final m in RegExp(r'(?<!\d)(0[23489][-\s]?\d{7}|05\d[-\s]?\d{7})(?!\d)').allMatches(text)) {
      final rawPhone = m.group(1)!.replaceAll(RegExp(r'[^0-9]'), '');
      if (rawPhone == '036021814') continue;
      final phoneStation = stationsByPhone[rawPhone];
      if (phoneStation != null) {
        return phoneStation;
      }
    }

    // 8. Check Hebrew branch/city aliases (sorted longest-first for specificity)
    final sortedAliases = hebrewBranchAliases.keys.toList()
      ..sort((a, b) => b.length.compareTo(a.length));
    for (final alias in sortedAliases) {
      if (text.contains(alias)) {
        final canonical = hebrewBranchAliases[alias]!;
        final compPrefix = company.isNotEmpty ? company : 'פז';
        // If non-Paz company, strip Paz-specific code if present
        if (compPrefix != 'פז') {
          final withoutCode = canonical.replaceAll(RegExp(r'\s*\(\d+\)'), '').trim();
          return '$compPrefix $withoutCode';
        }
        return '$compPrefix $canonical';
      }
    }

    // 9. Scan all Paz / Sonol / Delek / Dor Alon station names in the text
    Map<String, String> activeMap = pazStationsByCode;
    String activePrefix = company.isNotEmpty ? company : 'פז';
    if (company == 'סונול') activeMap = sonolStationsByCode;
    if (company == 'דלק') activeMap = delekStationsByCode;
    if (company == 'דור אלון') activeMap = dorAlonStationsByCode;

    final sortedEntries = activeMap.entries.toList()
      ..sort((a, b) => b.value.length.compareTo(a.value.length));
    for (final entry in sortedEntries) {
      if (entry.value.length >= 3 && text.contains(entry.value)) {
        return '$activePrefix ${entry.value} (${entry.key})';
      }
    }

    return '';
  }
